#!/usr/bin/env node
// Token pipeline (SPEC §9.0): docs/design/tokens.json (W3C design tokens, the
// Penpot export) → src/styles/tokens.css (CSS variables, Dark and Light) and
// src/lib/tokens.js (numbers JS needs: breakpoints, sizes). A small
// equivalent of Style Dictionary: resolves `{a.b}` references, emits semantic
// tokens only (never `palette.*`).
//
//   node scripts/tokens.mjs           write the files
//   node scripts/tokens.mjs --check   fail when the files drift from tokens.json,
//                                     or when UI code uses a raw color or an
//                                     unknown token
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
export const UI = join(here, '..');
export const SOURCE = join(UI, '..', 'docs', 'design', 'tokens.json');
export const CSS_OUT = join(UI, 'src', 'styles', 'tokens.css');
export const JS_OUT = join(UI, 'src', 'lib', 'tokens.js');

/** Flattens a token set into { 'a.b.c': {type, value} }. */
export function flatten(set, prefix = '', out = {}) {
  for (const [k, v] of Object.entries(set)) {
    if (k.startsWith('$')) continue;
    const path = prefix ? `${prefix}.${k}` : k;
    if (v && typeof v === 'object' && '$value' in v) out[path] = { type: v.$type, value: v.$value };
    else if (v && typeof v === 'object') flatten(v, path, out);
  }
  return out;
}

export function resolve(value, table, seen = []) {
  if (typeof value === 'string') {
    const whole = value.match(/^\{([^}]+)\}$/);
    if (whole) {
      const ref = whole[1];
      if (seen.includes(ref)) throw new Error(`token cycle: ${[...seen, ref].join(' → ')}`);
      const t = table[ref];
      if (!t) throw new Error(`unknown token reference {${ref}}`);
      return resolve(t.value, table, [...seen, ref]);
    }
    return value.replace(/\{([^}]+)\}/g, (_, ref) => String(resolve(`{${ref}}`, table, seen)));
  }
  if (Array.isArray(value)) return value.map((v) => resolve(v, table, seen));
  if (value && typeof value === 'object') {
    return Object.fromEntries(Object.entries(value).map(([k, v]) => [k, resolve(v, table, seen)]));
  }
  return value;
}

const px = (v) => (/^-?\d+(\.\d+)?$/.test(String(v)) ? (Number(v) === 0 ? '0' : `${v}px`) : String(v));
const family = (list) => [...list.map((f) => `"${f}"`), 'monospace'].join(', ');

/** CSS value for one resolved token, or null when it isn't emitted. */
export function cssValue(type, v) {
  switch (type) {
    case 'color':
      return String(v).toLowerCase();
    case 'fontFamilies':
      return family(Array.isArray(v) ? v : [v]);
    case 'fontSizes':
    case 'spacing':
    case 'borderRadius':
    case 'borderWidth':
    case 'sizing':
    case 'dimension':
      return px(v);
    case 'fontWeights':
    case 'opacity':
      return String(v);
    case 'typography':
      return `${v.fontWeight} ${px(v.fontSize)}/${v.lineHeight} ${family(v.fontFamily)}`;
    case 'shadow':
      return (Array.isArray(v) ? v : [v])
        .map((s) => `${s.inset ? 'inset ' : ''}${px(s.offsetX)} ${px(s.offsetY)} ${px(s.blur)} ${px(s.spread)} ${String(s.color).toLowerCase()}`)
        .join(', ');
    default:
      return null;
  }
}

export const varName = (path) => `--${path.replace(/\./g, '-')}`;

/** The variables of one theme: core (without palette) + the theme's semantic set. */
export function themeVars(doc, themeSet) {
  const core = flatten(doc.core);
  const theme = flatten(doc[themeSet]);
  const table = { ...core, ...theme };
  const vars = {};
  for (const [path, t] of Object.entries(table)) {
    if (path.startsWith('palette.')) continue; // semantic tokens only
    const css = cssValue(t.type, resolve(t.value, table));
    if (css != null) vars[varName(path)] = css;
  }
  return vars;
}

export function build(doc) {
  const themes = doc.$themes ?? [];
  const setOf = (name) => themes.find((t) => t.name === name)?.sets.find((s) => s.startsWith('theme/'));
  const dark = themeVars(doc, setOf('Dark') ?? 'theme/dark');
  const light = themeVars(doc, setOf('Light') ?? 'theme/light');
  const shared = Object.keys(dark).filter((k) => light[k] === dark[k]);
  const differs = Object.keys(dark).filter((k) => light[k] !== dark[k]);
  const block = (keys, vars, indent = '  ') => keys.map((k) => `${indent}${k}: ${vars[k]};`).join('\n');
  const css = `/* Generated by ui/scripts/tokens.mjs from docs/design/tokens.json. Do not edit. */
/* Theme precedence (§9.1): user choice (data-theme) > system. */

:root {
${block(shared, dark)}
}

:root,
:root[data-theme='dark'] {
  color-scheme: dark;
${block(differs, dark)}
}

:root[data-theme='light'] {
  color-scheme: light;
${block(differs, light)}
}

@media (prefers-color-scheme: light) {
  :root:not([data-theme]) {
    color-scheme: light;
${block(differs, light, '    ')}
  }
}
`;
  const num = (path) => Number(resolve(`{${path}}`, flatten(doc.core)));
  const core = flatten(doc.core);
  const pick = (prefix) =>
    Object.fromEntries(Object.keys(core).filter((k) => k.startsWith(prefix)).map((k) => [k.slice(prefix.length), num(k)]));
  const js = `// Generated by ui/scripts/tokens.mjs from docs/design/tokens.json. Do not edit.
export const breakpoint = ${JSON.stringify(pick('breakpoint.'))};
export const size = ${JSON.stringify(pick('size.'))};
export const space = ${JSON.stringify(pick('space.'))};
export const fontFamily = ${JSON.stringify(resolve('{font.family.ui}', core)[0])};
export const variables = ${JSON.stringify(Object.keys(dark).sort())};
`;
  return { css, js, variables: new Set(Object.keys(dark)) };
}

function walk(dir, out = []) {
  for (const f of readdirSync(dir)) {
    const p = join(dir, f);
    if (statSync(p).isDirectory()) walk(p, out);
    else if (/\.(svelte|css|js)$/.test(f)) out.push(p);
  }
  return out;
}

/**
 * UI code uses semantic tokens only: no raw colors outside tokens.css (and the
 * terminal theme, which comes from kitty.conf), and every `var(--…)` names a
 * token or a variable the file defines itself.
 */
export function lint(srcDir, variables) {
  const problems = [];
  for (const file of walk(srcDir)) {
    const rel = relative(srcDir, file);
    if (rel === join('styles', 'tokens.css') || rel === join('lib', 'tokens.js')) continue;
    const text = readFileSync(file, 'utf8');
    const style = file.endsWith('.js') ? '' : file.endsWith('.css') ? text : (text.match(/<style[^>]*>([\s\S]*?)<\/style>/g) ?? []).join('\n');
    const local = new Set([...text.matchAll(/(--[a-z0-9-]+)\s*:/gi)].map((m) => m[1]));
    for (const m of text.matchAll(/var\((--[a-z0-9-]+)(\$\{)?/gi)) {
      // `var(--color-role-${n})`: a family of tokens.
      const known = m[2] ? [...variables].some((v) => v.startsWith(m[1])) : variables.has(m[1]) || local.has(m[1]);
      if (!known) problems.push(`${rel}: unknown token ${m[1]}${m[2] ? '…' : ''}`);
    }
    for (const m of style.matchAll(/#[0-9a-f]{3,8}\b|rgba?\(|hsla?\(/gi)) problems.push(`${rel}: raw color ${m[0]} (use a semantic token)`);
  }
  return problems;
}

export function check() {
  const doc = JSON.parse(readFileSync(SOURCE, 'utf8'));
  const { css, js, variables } = build(doc);
  const problems = [];
  if (readFileSync(CSS_OUT, 'utf8') !== css) problems.push(`${relative(UI, CSS_OUT)} drifted from tokens.json: run npm run tokens`);
  if (readFileSync(JS_OUT, 'utf8') !== js) problems.push(`${relative(UI, JS_OUT)} drifted from tokens.json: run npm run tokens`);
  problems.push(...lint(join(UI, 'src'), variables));
  return problems;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  if (process.argv.includes('--check')) {
    const problems = check();
    for (const p of problems) console.error(p);
    if (problems.length) process.exit(1);
    console.log('tokens: in sync, UI uses semantic tokens only');
  } else {
    const { css, js, variables } = build(JSON.parse(readFileSync(SOURCE, 'utf8')));
    writeFileSync(CSS_OUT, css);
    writeFileSync(JS_OUT, js);
    console.log(`tokens: ${variables.size} variables → ${relative(UI, CSS_OUT)}, ${relative(UI, JS_OUT)}`);
  }
}
