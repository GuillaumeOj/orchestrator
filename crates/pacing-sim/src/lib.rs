use governor::jiff::tz::TimeZone;
use governor::jiff::{SignedDuration, Timestamp};
use governor::{
    ActionKind, AgentId, AllocationId, BudgetAllocation, Curve, Day, Decision, EntryId, Governor, GovernorAction,
    PacingPolicy, PressureState, Provenance, Release, Tier, ToolCallRequest, TurnKind, TurnRequest, UsageSample,
    Verdict, WeeklyPlan, Window, WindowReading, WorkBlock, WorkingCalendar,
};
use serde::{Deserialize, Serialize};

// ------------------------------------------------------------------ scenario

#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct SimAllocation {
    pub allocation: BudgetAllocation,
    /// Agents working through this allocation's backlog in parallel.
    pub agents: u32,
}

/// Hidden truth of the simulated plan and agents.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct SimModel {
    /// Weekly pp an agent burns per hour while working.
    pub agent_rate_pct_h: f64,
    /// ± relative jitter of the per-minute burn.
    pub rate_jitter: f64,
    /// 5h-window pp per weekly pp.
    pub five_hour_per_weekly_pct: f64,
    /// True cost units per weekly pp (the Governor has to learn it).
    pub cost_per_pct: f64,
    /// Turn size range, weekly pp.
    pub turn_pct_min: f64,
    pub turn_pct_max: f64,
    /// Share of follow-up turns that start by themselves (background work, FR-410).
    pub self_started_share: f64,
    /// Offer work outside working time (otherwise agents wait for the next block).
    pub offer_off_hours: bool,
}

impl Default for SimModel {
    fn default() -> Self {
        SimModel {
            agent_rate_pct_h: 0.8,
            rate_jitter: 0.25,
            five_hour_per_weekly_pct: 5.0,
            cost_per_pct: 10.0,
            turn_pct_min: 0.2,
            turn_pct_max: 0.6,
            self_started_share: 0.15,
            offer_off_hours: false,
        }
    }
}

