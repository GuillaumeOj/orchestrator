/// SplitMix64: tiny, deterministic.
#[derive(Clone, Debug)]
pub struct Rng(u64);

impl Rng {
    pub fn new(seed: u64) -> Self {
        Rng(seed ^ 0x9E37_79B9_7F4A_7C15)
    }

    pub fn next_u64(&mut self) -> u64 {
        self.0 = self.0.wrapping_add(0x9E37_79B9_7F4A_7C15);
        let mut z = self.0;
        z = (z ^ (z >> 30)).wrapping_mul(0xBF58_476D_1CE4_E5B9);
        z = (z ^ (z >> 27)).wrapping_mul(0x94D0_49BB_1331_11EB);
        z ^ (z >> 31)
    }

    /// Uniform in [0, 1).
    pub fn f64(&mut self) -> f64 {
        (self.next_u64() >> 11) as f64 / (1u64 << 53) as f64
    }

    pub fn range(&mut self, lo: f64, hi: f64) -> f64 {
        lo + (hi - lo) * self.f64()
    }
}

fn ts(s: &str) -> Timestamp {
    s.parse().expect("valid timestamp")
}

fn add_min(t: Timestamp, m: i64) -> Timestamp {
    t.checked_add(SignedDuration::from_mins(m)).expect("in range")
}

impl Scenario {
    /// The default calendar: Mon–Thu 09–19, Fri 09–13 plus 13–17 at half weight,
    /// Europe/Paris, week of Monday 2026-10-19 09:00 (the weekly reset).
    pub fn default_calendar() -> WorkingCalendar {
        let mut blocks: Vec<WorkBlock> = [Day::Mon, Day::Tue, Day::Wed, Day::Thu]
            .iter()
            .map(|&day| WorkBlock { day, start: time(9, 0, 0, 0), end: time(19, 0, 0, 0), weight: 1.0 })
            .collect();
        blocks.push(WorkBlock { day: Day::Fri, start: time(9, 0, 0, 0), end: time(13, 0, 0, 0), weight: 1.0 });
        blocks.push(WorkBlock { day: Day::Fri, start: time(13, 0, 0, 0), end: time(17, 0, 0, 0), weight: 0.5 });
        WorkingCalendar { time_zone: "Europe/Paris".into(), blocks, holidays: Vec::new() }
    }

    pub fn default_allocations() -> Vec<SimAllocation> {
        let a = |id: &str, target: &str, weight: f64, tier: Tier| SimAllocation {
            allocation: BudgetAllocation { id: id.into(), target: target.into(), weight, tier, hard_cap_pct: None },
            agents: 1,
        };
        vec![
            a("A", "project A", 50.0, Tier::High),
            a("B", "project B", 30.0, Tier::Normal),
            a("C", "project C · search v2", 20.0, Tier::Low),
        ]
    }

    pub fn default_policy() -> PacingPolicy {
        PacingPolicy { initial_cost_per_pct: 8.0, ..PacingPolicy::default() }
    }

    /// Generate a synthetic week. Tasks arrive in working time, split across
    /// allocations by weight; interactive bursts fall in working time; usage
    /// outside the app falls anywhere on weekdays between 08:00 and 23:00.
    pub fn synthetic(p: &SyntheticParams) -> Scenario {
        let week_start = ts("2026-10-19T07:00:00Z");
        let reset_at = ts("2026-10-26T08:00:00Z");
        let calendar = Scenario::default_calendar();
        let allocations = Scenario::default_allocations();
        let curve = Curve::build(&calendar, week_start, reset_at, 0.0).expect("calendar");
        let mut rng = Rng::new(p.seed);
        let total_h = curve.total_hours();
        let random_work_time =
            |rng: &mut Rng, upto: f64| curve.time_at_hours(rng.range(0.0, total_h * upto)).expect("inside the week");

        let autonomous = (p.demand_pct - p.interactive_pct - p.unattributed_pct).max(0.0);
        let weight_sum: f64 = allocations.iter().map(|a| a.allocation.weight).sum();
        // Each allocation gets enough agents for its backlog at 80 % utilisation.
        let model = SimModel::default();
        let agent_week = model.agent_rate_pct_h * curve.active_hours_between(week_start, reset_at) * 0.8;
        let mut allocations = allocations;
        for a in &mut allocations {
            let share = autonomous * a.allocation.weight / weight_sum;
            a.agents = ((share / agent_week).ceil() as u32).max(1);
        }
        let mut tasks = Vec::new();
        let mut critical_left = p.critical_pct;
        for a in &allocations {
            let share = autonomous * a.allocation.weight / weight_sum;
            let mut sum = 0.0;
            while sum < share - 1e-9 {
                let work = rng.range(1.0, 4.0).min(share - sum).max(0.1);
                sum += work;
                // Some critical tasks on the high-tier allocation, up to `critical_pct`.
                let critical = a.allocation.tier == Tier::High && critical_left >= work && rng.f64() < 0.2;
                if critical {
                    critical_left -= work;
                }
                let tier = critical.then_some(Tier::Critical);
                tasks.push(TaskSpec {
                    allocation: a.allocation.id.clone(),
                    arrive_at: random_work_time(&mut rng, 0.9),
                    work_pct: work,
                    tier,
                });
            }
        }
        tasks.sort_by(|x, y| x.arrive_at.cmp(&y.arrive_at).then_with(|| x.allocation.cmp(&y.allocation)));

        let bursts = |rng: &mut Rng, total: f64, lo: f64, hi: f64, at: &mut dyn FnMut(&mut Rng) -> Timestamp| {
            let mut v = Vec::new();
            let mut sum = 0.0;
            while sum < total - 1e-9 {
                let pct = rng.range(lo, hi).min(total - sum);
                sum += pct;
                let start = at(rng);
                v.push(Burst { start, minutes: rng.range(30.0, 90.0).round() as i64, pct });
            }
            v.sort_by_key(|b| b.start);
            v
        };
        let interactive = bursts(&mut rng, p.interactive_pct, 0.5, 1.5, &mut |rng| random_work_time(rng, 1.0));
        let tz = TimeZone::get("Europe/Paris").expect("tz");
        let unattributed = bursts(&mut rng, p.unattributed_pct, 0.5, 2.0, &mut |rng| {
            let day = (rng.f64() * 5.0).floor() as i64;
            let minute = rng.range(8.0 * 60.0, 23.0 * 60.0).round() as i64;
            let local_midnight =
                week_start.to_zoned(tz.clone()).date().to_zoned(tz.clone()).expect("midnight").timestamp();
            add_min(local_midnight, day * 1440 + minute)
        });

        Scenario {
            name: p.name.clone(),
            week_start,
            reset_at,
            calendar,
            reserve_pct: 10.0,
            off_hours_allowance_pct: 0.0,
            shadow_mode: p.shadow_mode,
            allocations,
            policy: Scenario::default_policy(),
            model,
            seed: p.seed,
            tasks,
            interactive,
            unattributed,
            // Wednesday 14:00 Paris: someone burns the 5h window outside the app.
            forced_limit: p
                .forced_limit
                .then(|| ForcedLimit { at: ts("2026-10-21T12:00:00Z"), window: Window::FiveHour }),
            // Thursday 10:00 Paris: sprint for the rest of the day.
            sprint: p.sprint.then(|| SprintSpec { at: ts("2026-10-22T08:00:00Z"), extra_pct: 4.0 }),
        }
    }

    pub fn plan(&self) -> WeeklyPlan {
        WeeklyPlan {
            id: self.name.clone(),
            week_start: self.week_start,
            reset_at: self.reset_at,
            calendar: self.calendar.clone(),
            reserve_pct: self.reserve_pct,
            off_hours_allowance_pct: self.off_hours_allowance_pct,
            shadow_mode: self.shadow_mode,
            allocations: self.allocations.iter().map(|a| a.allocation.clone()).collect(),
        }
    }
}

