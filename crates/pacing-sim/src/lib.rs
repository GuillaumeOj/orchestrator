//! Week simulator for the Governor (SPEC FR-820, NFR-9).
//!
//! Replays a synthetic or recorded week minute by minute: tasks arriving per
//! allocation and worked through by agents, the user's interactive bursts,
//! usage outside the app, and optionally a forced plan-limit 429. The true
//! usage is known to the simulator only; the Governor sees what Claude Code
//! would show it: integer statusline percentages on each agent's API
//! responses, attributed cost, StopFailure on a 429.

use std::collections::{BTreeMap, VecDeque};
use std::fmt::Write as _;

