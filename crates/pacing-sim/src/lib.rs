#[derive(Clone, Debug, Default, PartialEq, Serialize)]
pub struct WaitStats {
    pub count: u64,
    pub mean_min: f64,
    pub p95_min: f64,
    pub max_min: f64,
}

impl WaitStats {
    fn from(mut v: Vec<f64>) -> Self {
        if v.is_empty() {
            return WaitStats::default();
        }
        v.sort_by(|a, b| a.total_cmp(b));
        let n = v.len();
        WaitStats {
            count: n as u64,
            mean_min: v.iter().sum::<f64>() / n as f64,
            p95_min: v[((n as f64 * 0.95).ceil() as usize).clamp(1, n) - 1],
            max_min: v[n - 1],
        }
    }
}

