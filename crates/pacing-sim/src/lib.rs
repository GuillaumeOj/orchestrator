#[derive(Clone, Debug, PartialEq)]
enum StreamState {
    /// No turn: may request one when it has a task.
    Idle,
    Waiting(EntryId),
    Running {
        turn_left: f64,
    },
}

#[derive(Clone, Debug)]
struct Stream {
    agent: AgentId,
    allocation: AllocationId,
    state: StreamState,
    /// (task index, remaining pp)
    task: Option<(usize, f64)>,
    next_self_started: bool,
}

struct Truth {
    weekly: f64,
    five: f64,
    five_reset: Option<Timestamp>,
    forced_until: Option<Timestamp>,
}

impl Truth {
    fn roll(&mut self, now: Timestamp) {
        if self.five_reset.is_some_and(|r| now >= r) {
            self.five = 0.0;
            self.five_reset = None;
        }
        if self.forced_until.is_some_and(|r| now >= r) {
            self.forced_until = None;
        }
    }

    fn spend(&mut self, pct: f64, f5: f64, now: Timestamp) {
        if self.five_reset.is_none() {
            self.five_reset = Some(add_min(now, 300));
        }
        self.weekly += pct;
        self.five += pct * f5;
    }

    /// The window a call would hit, if any.
    fn exhausted(&self) -> Option<(Window, Timestamp)> {
        if self.five >= 100.0 || self.forced_until.is_some() {
            return Some((Window::FiveHour, self.five_reset.or(self.forced_until).expect("window open")));
        }
        None
    }

    fn reading(&self, sc: &Scenario) -> (Option<WindowReading>, Option<WindowReading>) {
        let five = self.five_reset.map(|r| WindowReading {
            used_pct: if self.forced_until.is_some() { 100.0 } else { self.five.floor().min(100.0) },
            resets_at: r,
        });
        let weekly = Some(WindowReading { used_pct: self.weekly.floor().min(100.0), resets_at: sc.reset_at });
        (five, weekly)
    }
}

/// Run a scenario. Deterministic for a given scenario.
pub fn run(sc: &Scenario) -> SimResult {
    let plan = sc.plan();
    let mut gov = Governor::new(plan, sc.policy.clone(), sc.week_start).expect("valid plan");
    let curve =
        Curve::build(&sc.calendar, sc.week_start, sc.reset_at, sc.off_hours_allowance_pct).expect("valid calendar");
    let tz = TimeZone::get(&sc.calendar.time_zone).expect("tz");
    let m = &sc.model;
    let mut rng = Rng::new(sc.seed.wrapping_mul(31).wrapping_add(7));
    let user = AgentId::from("user");

    let mut streams: Vec<Stream> = sc
        .allocations
        .iter()
        .flat_map(|a| {
            (0..a.agents).map(move |i| Stream {
                agent: agent_name(&a.allocation.id, i),
                allocation: a.allocation.id.clone(),
                state: StreamState::Idle,
                task: None,
                next_self_started: false,
            })
        })
        .collect();
    let mut backlog: BTreeMap<AllocationId, VecDeque<usize>> = BTreeMap::new();
    let mut next_task = 0usize;
    let mut done_pct: BTreeMap<AllocationId, f64> = BTreeMap::new();
    let mut tasks_done: BTreeMap<AllocationId, usize> = BTreeMap::new();
    let mut truth = Truth { weekly: 0.0, five: 0.0, five_reset: None, forced_until: None };
    let mut rows = Vec::new();
    let mut limit_hits: Vec<LimitHit> = Vec::new();
    let mut weekly_exhausted_at = None;
    let mut interactive_blocked_min = 0i64;
    let mut self_started_turns = 0u64;
    let mut weekly_at_end_of_work = 0.0;
    let mut max_weekly: f64 = 0.0;
    let mut forced = sc.forced_limit.clone();
    let mut sprint = sc.sprint.clone();

    let minutes = (sc.reset_at.as_second() - sc.week_start.as_second()) / 60;
    for minute in 0..minutes {
        let now = add_min(sc.week_start, minute);
        truth.roll(now);
        let working = curve.weight_at(now) > 0.0;
        let offering = working || m.offer_off_hours;

        if forced.take_if(|f| now >= f.at).is_some() {
            if truth.five_reset.is_none() {
                truth.five_reset = Some(add_min(now, 300));
            }
            truth.forced_until = truth.five_reset;
            truth.five = 100.0;
        }
        if let Some(s) = sprint.take_if(|s| now >= s.at) {
            let _ = gov.start_sprint(s.extra_pct, now);
        }

        // Arrivals.
        while next_task < sc.tasks.len() && sc.tasks[next_task].arrive_at <= now {
            backlog.entry(sc.tasks[next_task].allocation.clone()).or_default().push_back(next_task);
            next_task += 1;
        }

        // Control loop.
        let released = gov.tick(now);
        apply_releases(&mut streams, &mut gov, released, sc, &mut rng, now);

        // Idle streams ask for turns.
        for s in streams.iter_mut() {
            if s.state != StreamState::Idle || !offering {
                continue;
            }
            if s.task.is_none() {
                if let Some(t) = backlog.get_mut(&s.allocation).and_then(|q| q.pop_front()) {
                    s.task = Some((t, sc.tasks[t].work_pct));
                    s.next_self_started = false;
                }
            }
            let Some((t, _)) = s.task else { continue };
            let spec = &sc.tasks[t];
            let tier = spec.tier.unwrap_or_else(|| alloc_tier(sc, &s.allocation));
            let self_started = s.next_self_started;
            if self_started {
                self_started_turns += 1;
            }
            let mut req = TurnRequest::task(s.agent.clone(), s.allocation.clone(), tier);
            if self_started {
                req.kind = TurnKind::Continue;
                req.self_started = true;
            }
            let d = gov.request_turn(req, now);
            set_from_decision(s, &d, sc, &mut rng);
        }

        // Running agents: one tool call and one API response per minute.
        let mut samples = Vec::new();
        for i in 0..streams.len() {
            let StreamState::Running { turn_left } = streams[i].state else { continue };
            let agent = streams[i].agent.clone();
            let d = gov.tool_call(&ToolCallRequest { agent: agent.clone(), interactive: false }, now);
            match d.effective {
                Verdict::Admit => {}
                _ => {
                    streams[i].state = match queued_entry(&gov, &agent) {
                        Some(e) => StreamState::Waiting(e),
                        None => StreamState::Idle,
                    };
                    continue;
                }
            }
            if let Some((window, resets)) = truth.exhausted() {
                limit_hits.push(LimitHit { ts: now, window, working_hours: working });
                let resp = gov.rate_limit_hit(Some(&agent), window, resets, now);
                streams[i].state = match resp.entry {
                    Some(e) => StreamState::Waiting(e),
                    None => StreamState::Idle,
                };
                let released = gov.turn_ended(&agent, now);
                apply_releases(&mut streams, &mut gov, released, sc, &mut rng, now);
                continue;
            }
            let burn = m.agent_rate_pct_h / 60.0 * (1.0 + m.rate_jitter * (2.0 * rng.f64() - 1.0));
            truth.spend(burn, m.five_hour_per_weekly_pct, now);
            samples.push((agent.clone(), burn));
            let (t, left) = streams[i].task.expect("running with a task");
            let left = left - burn;
            *done_pct.entry(streams[i].allocation.clone()).or_insert(0.0) += burn;
            let turn_left = turn_left - burn;
            if left <= 0.0 {
                streams[i].task = None;
                *tasks_done.entry(streams[i].allocation.clone()).or_insert(0) += 1;
            } else {
                streams[i].task = Some((t, left));
            }
            if left <= 0.0 || turn_left <= 0.0 {
                streams[i].state = StreamState::Idle;
                streams[i].next_self_started = left > 0.0 && working && rng.f64() < m.self_started_share;
                let released = gov.turn_ended(&agent, now);
                apply_releases(&mut streams, &mut gov, released, sc, &mut rng, now);
            } else {
                streams[i].state = StreamState::Running { turn_left };
            }
        }

        // The user's own work in a pane: never held by the Governor.
        let interactive_rate = burst_rate(&sc.interactive, now);
        if interactive_rate > 0.0 {
            let d = gov.tool_call(&ToolCallRequest { agent: user.clone(), interactive: true }, now);
            debug_assert!(d.effective.is_admit());
            if truth.exhausted().is_some() {
                interactive_blocked_min += 1;
            } else {
                truth.spend(interactive_rate, m.five_hour_per_weekly_pct, now);
                samples.push((user.clone(), interactive_rate));
            }
        }

        // Usage outside the app: invisible except through later readings.
        let outside = burst_rate(&sc.unattributed, now);
        if outside > 0.0 && truth.exhausted().is_none() {
            truth.spend(outside, m.five_hour_per_weekly_pct, now);
        }

        // Statusline samples for every API response of this minute.
        let (five, weekly) = truth.reading(sc);
        for (agent, pct) in samples {
            gov.ingest(&UsageSample {
                ts: now,
                agent: Some(agent),
                cost_delta: pct * m.cost_per_pct,
                five_hour: five,
                weekly,
                provenance: Provenance::Observed,
            });
        }

        if truth.weekly >= 100.0 && weekly_exhausted_at.is_none() {
            weekly_exhausted_at = Some(now);
            limit_hits.push(LimitHit { ts: now, window: Window::Weekly, working_hours: working });
        }
        max_weekly = max_weekly.max(truth.weekly);
        if working {
            weekly_at_end_of_work = truth.weekly;
        }

        if minute % 5 == 0 {
            let snap = gov.snapshot(now);
            rows.push(Row {
                ts: now,
                local: now.to_zoned(tz.clone()).strftime("%a %H:%M").to_string(),
                true_weekly: truth.weekly,
                observed_weekly: weekly.map(|w| w.used_pct),
                used: snap.used,
                used_central: snap.used_central,
                provenance: snap.provenance,
                plan: snap.plan,
                ideal: snap.ideal,
                error: snap.error,
                state: snap.state,
                live_cap: snap.live_cap,
                live: snap.live_autonomous,
                queued: snap.queued,
                true_five_hour: truth.five,
                five_hour: snap.five_hour,
                five_hour_projected: snap.five_hour_projected,
                five_hour_guard: snap.five_hour_guard,
                burn: snap.burn_pct_per_hour,
                k: snap.calibration.cost_per_weekly_pct,
                confidence: snap.calibration.confidence,
                unattributed_so_far: snap.unattributed_so_far,
                reserve_left: snap.reserve_left,
                interactive_used: snap.interactive_used,
            });
        }
    }

    let summary = summarize(SummaryInputs {
        sc,
        gov: &gov,
        final_weekly: truth.weekly,
        weekly_at_end_of_work,
        max_weekly,
        weekly_exhausted_at,
        limit_hits,
        interactive_blocked_min,
        self_started_turns,
        done_pct,
        tasks_done,
    });
    SimResult { summary, rows, actions: gov.actions().to_vec() }
}

/// The agent of a stream: `<allocation>-<n>`, numbered from 1.
fn agent_name(allocation: &AllocationId, index: u32) -> AgentId {
    AgentId(format!("{allocation}-{}", index + 1))
}

/// Weekly pp per minute from the bursts active at `now`.
fn burst_rate(bursts: &[Burst], now: Timestamp) -> f64 {
    bursts
        .iter()
        .filter(|b| now >= b.start && now < add_min(b.start, b.minutes))
        .map(|b| b.pct / b.minutes as f64)
        .sum()
}

fn alloc_tier(sc: &Scenario, id: &AllocationId) -> Tier {
    sc.allocations.iter().find(|a| &a.allocation.id == id).map_or(Tier::Normal, |a| a.allocation.tier)
}

fn queued_entry(gov: &Governor, agent: &AgentId) -> Option<EntryId> {
    gov.queue().iter().find(|e| &e.agent == agent).map(|e| e.id)
}

fn new_turn(sc: &Scenario, rng: &mut Rng) -> StreamState {
    StreamState::Running { turn_left: rng.range(sc.model.turn_pct_min, sc.model.turn_pct_max) }
}

fn set_from_decision(s: &mut Stream, d: &Decision, sc: &Scenario, rng: &mut Rng) {
    s.next_self_started = false;
    s.state = match &d.effective {
        Verdict::Admit => new_turn(sc, rng),
        Verdict::Queue { entry: Some(e), .. } => StreamState::Waiting(*e),
        Verdict::Queue { entry: None, .. } | Verdict::Deny { .. } => StreamState::Idle,
    };
}

fn apply_releases(
    streams: &mut [Stream],
    gov: &mut Governor,
    released: Vec<Release>,
    sc: &Scenario,
    rng: &mut Rng,
    now: Timestamp,
) {
    for r in released {
        match streams.iter_mut().find(|s| s.agent == r.agent) {
            Some(s) if s.state == StreamState::Waiting(r.entry) && s.task.is_some() => s.state = new_turn(sc, rng),
            _ => {
                // The Governor released a turn this stream cannot run: a mismatch to fix,
                // not to hide. Release builds give the slot back.
                debug_assert!(false, "release for {} which is not waiting on entry {}", r.agent, r.entry);
                let more = gov.turn_ended(&r.agent, now);
                apply_releases(streams, gov, more, sc, rng, now);
            }
        }
    }
}

struct SummaryInputs<'a> {
    sc: &'a Scenario,
    gov: &'a Governor,
    final_weekly: f64,
    weekly_at_end_of_work: f64,
    max_weekly: f64,
    weekly_exhausted_at: Option<Timestamp>,
    limit_hits: Vec<LimitHit>,
    interactive_blocked_min: i64,
    self_started_turns: u64,
    done_pct: BTreeMap<AllocationId, f64>,
    tasks_done: BTreeMap<AllocationId, usize>,
}

fn summarize(i: SummaryInputs<'_>) -> Summary {
    let sc = i.sc;
    let final_snap = i.gov.snapshot(sc.reset_at);
    let demand_pct = sc.tasks.iter().map(|t| t.work_pct).sum::<f64>()
        + sc.interactive.iter().map(|b| b.pct).sum::<f64>()
        + sc.unattributed.iter().map(|b| b.pct).sum::<f64>();
    let mut actions: BTreeMap<String, u64> = BTreeMap::new();
    let mut queued_at: BTreeMap<EntryId, (Timestamp, AgentId)> = BTreeMap::new();
    let mut waits = Vec::new();
    let mut waits_by_tier: BTreeMap<String, Vec<f64>> = BTreeMap::new();
    let mut transitions: Vec<(Timestamp, PressureState)> = vec![(sc.week_start, PressureState::Green)];
    let tiers: BTreeMap<AgentId, Tier> = sc
        .allocations
        .iter()
        .flat_map(|a| (0..a.agents).map(move |n| (agent_name(&a.allocation.id, n), a.allocation.tier)))
        .collect();
    for a in i.gov.actions() {
        *actions.entry(a.kind_name().to_owned()).or_insert(0) += 1;
        match &a.action {
            ActionKind::Queue { entry: Some(e), agent, .. } => {
                queued_at.insert(*e, (a.ts, agent.clone()));
            }
            ActionKind::Release { entry, .. } | ActionKind::RunNow { entry, .. } => {
                if let Some((t, agent)) = queued_at.remove(entry) {
                    let w = (a.ts.as_second() - t.as_second()) as f64 / 60.0;
                    waits.push(w);
                    let tier = tiers.get(&agent).copied().unwrap_or(Tier::Normal);
                    waits_by_tier.entry(format!("{tier:?}").to_lowercase()).or_default().push(w);
                }
            }
            ActionKind::StateChange { to, .. } => transitions.push((a.ts, *to)),
            _ => {}
        }
    }
    let mut state_minutes: BTreeMap<String, i64> = BTreeMap::new();
    let mut min_dwell: Option<i64> = None;
    for (n, (t, s)) in transitions.iter().enumerate() {
        let end = transitions.get(n + 1).map_or(sc.reset_at, |x| x.0);
        let d = (end.as_second() - t.as_second()) / 60;
        *state_minutes.entry(s.to_string()).or_insert(0) += d;
        if n + 1 < transitions.len() {
            min_dwell = Some(min_dwell.map_or(d, |m: i64| m.min(d)));
        }
    }
    let stats = i.gov.stats();
    let queued_for_pacing = stats
        .queued_by_reason
        .iter()
        .filter(|(k, _)| k.as_str() != "off_hours" && k.as_str() != "paused_all")
        .map(|(_, v)| v)
        .sum();
    let allocations = sc
        .allocations
        .iter()
        .map(|a| {
            let id = &a.allocation.id;
            AllocationSummary {
                id: id.clone(),
                weight: a.allocation.weight,
                tier: a.allocation.tier,
                demand_pct: sc.tasks.iter().filter(|t| &t.allocation == id).map(|t| t.work_pct).sum(),
                done_pct: i.done_pct.get(id).copied().unwrap_or(0.0),
                tasks: sc.tasks.iter().filter(|t| &t.allocation == id).count(),
                tasks_done: i.tasks_done.get(id).copied().unwrap_or(0),
            }
        })
        .collect();
    Summary {
        scenario: sc.name.clone(),
        shadow_mode: sc.shadow_mode,
        demand_pct,
        final_weekly_pct: i.final_weekly,
        weekly_at_end_of_work: i.weekly_at_end_of_work,
        max_weekly_pct: i.max_weekly,
        weekly_exhausted_at: i.weekly_exhausted_at,
        limit_hits: i.limit_hits,
        queued: stats.queued,
        queued_for_pacing,
        queued_by_reason: stats.queued_by_reason.clone(),
        waits: WaitStats::from(waits),
        waits_by_tier: waits_by_tier.into_iter().map(|(k, v)| (k, WaitStats::from(v))).collect(),
        tool_calls_denied: stats.tool_calls_denied,
        shadow_overrides: stats.shadow_overrides,
        self_started_turns: i.self_started_turns,
        actions,
        state_minutes,
        state_changes: (transitions.len() - 1) as u64,
        min_dwell_min: min_dwell,
        interactive_blocked_min: i.interactive_blocked_min,
        allocations,
        final_k: final_snap.calibration.cost_per_weekly_pct,
        true_k: sc.model.cost_per_pct,
        final_confidence: final_snap.calibration.confidence,
        final_error_pp: final_snap.error,
    }
}

impl Summary {
    /// Human-readable report.
    pub fn render(&self) -> String {
        let mut s = String::new();
        let _ = writeln!(
            s,
            "scenario            {}{}",
            self.scenario,
            if self.shadow_mode { " (shadow mode)" } else { "" }
        );
        let _ = writeln!(s, "demand              {:.1} % of the weekly limit", self.demand_pct);
        let _ = writeln!(
            s,
            "weekly used         {:.1} % at reset ({:.1} % at end of working time, max {:.1} %)",
            self.final_weekly_pct, self.weekly_at_end_of_work, self.max_weekly_pct
        );
        let _ = writeln!(
            s,
            "weekly limit hit    {}",
            self.weekly_exhausted_at.map_or("never".to_owned(), |t| t.to_string())
        );
        if self.limit_hits.is_empty() {
            let _ = writeln!(s, "429s                none");
        } else {
            let first = &self.limit_hits[0];
            let _ = writeln!(
                s,
                "429s                {} (first {} {:?}, {})",
                self.limit_hits.len(),
                first.ts,
                first.window,
                if first.working_hours { "working hours" } else { "off-hours" }
            );
        }
        let _ = writeln!(s, "queued turns        {} ({} for pacing)", self.queued, self.queued_for_pacing);
        for (k, v) in &self.queued_by_reason {
            let _ = writeln!(s, "  {k:<22}{v}");
        }
        let _ = writeln!(
            s,
            "queue waits         n={} mean {:.0} min, p95 {:.0} min, max {:.0} min",
            self.waits.count, self.waits.mean_min, self.waits.p95_min, self.waits.max_min
        );
        for (k, w) in &self.waits_by_tier {
            let _ = writeln!(s, "  {k:<22}n={} mean {:.0} min, max {:.0} min", w.count, w.mean_min, w.max_min);
        }
        let _ = writeln!(s, "tool calls denied   {}", self.tool_calls_denied);
        if self.shadow_mode {
            let _ = writeln!(s, "shadow overrides    {}", self.shadow_overrides);
        }
        let _ = writeln!(s, "self-started turns  {}", self.self_started_turns);
        let _ =
            writeln!(s, "interactive blocked {} min (by the API, never by the Governor)", self.interactive_blocked_min);
        let _ = writeln!(
            s,
            "states              {} changes, shortest stay {} min",
            self.state_changes,
            self.min_dwell_min.map_or("-".to_owned(), |m| m.to_string())
        );
        for (k, v) in &self.state_minutes {
            let _ = writeln!(s, "  {k:<22}{:.1} h", *v as f64 / 60.0);
        }
        let _ = writeln!(s, "actions");
        for (k, v) in &self.actions {
            let _ = writeln!(s, "  {k:<22}{v}");
        }
        let _ = writeln!(s, "allocations         weight tier    demand   done   tasks");
        for a in &self.allocations {
            let _ = writeln!(
                s,
                "  {:<18}{:>5.0}  {:<7}{:>6.1}  {:>5.1}  {}/{}",
                a.id.0,
                a.weight,
                format!("{:?}", a.tier).to_lowercase(),
                a.demand_pct,
                a.done_pct,
                a.tasks_done,
                a.tasks
            );
        }
        let _ = writeln!(
            s,
            "estimator           k {:.2} (true {:.2}), confidence {:.2}; final error {:+.1} pp",
            self.final_k, self.true_k, self.final_confidence, self.final_error_pp
        );
        s
    }
}

/// CSV of the curves, one row per 5 minutes.
pub fn csv(rows: &[Row]) -> String {
    let mut s = String::from(
        "ts,local,true_weekly,observed_weekly,used,used_central,provenance,plan,ideal,error,state,live_cap,live,queued,true_five_hour,five_hour,five_hour_projected,five_hour_guard,burn,k,confidence,unattributed_so_far,reserve_left,interactive_used\n",
    );
    let opt = |v: Option<f64>| v.map_or(String::new(), |x| format!("{x:.2}"));
    for r in rows {
        let _ = writeln!(
            s,
            "{},{},{:.3},{},{:.3},{:.3},{:?},{:.3},{:.3},{:.3},{},{},{},{},{:.2},{},{},{},{:.4},{:.3},{:.3},{:.3},{:.3},{:.3}",
            r.ts,
            r.local,
            r.true_weekly,
            opt(r.observed_weekly),
            r.used,
            r.used_central,
            r.provenance,
            r.plan,
            r.ideal,
            r.error,
            r.state,
            r.live_cap,
            r.live,
            r.queued,
            r.true_five_hour,
            opt(r.five_hour),
            opt(r.five_hour_projected),
            r.five_hour_guard as u8,
            r.burn,
            r.k,
            r.confidence,
            r.unattributed_so_far,
            r.reserve_left,
            r.interactive_used
        );
    }
    s
}
